#!/usr/bin/env python3
"""신청기한 파서 점검 — `python3 scripts/check_period.py`

원천이 주는 '신청기한' 은 자유 서술이다. 45건을 세어 보니 절반(51%)은 날짜가
아예 없고, 날짜가 있는 것도 표기가 제각각이었다. 파서가 여기서 틀리면 시행중인
제도가 '종료' 로 찍히고 noindex 까지 붙으므로(YMYL), 표기별 기대값을 표로 박아
둔다. 파서를 손대면 이 스크립트부터 돌린다.

원칙: **단서 없는 날짜 하나는 아무 쪽에도 넣지 않는다.** 틀린 마감일을 적느니
기간을 비워 두는 편이 낫다.
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from collect.adapters.bojo24 import ALWAYS_TOKENS, parse_period  # noqa: E402

# (원문, 기대 start, 기대 end)
CASES = [
    # ── 구간이 분명한 표기 ──
    ("2026-03-02 ~ 2027-02-26",              "2026-03-02", "2027-02-26"),
    ("2026.03.02 ~ 2027.02.26",              "2026-03-02", "2027-02-26"),
    ("20260302~20270226",                    "2026-03-02", "2027-02-26"),
    ("2026년 3월 2일 ~ 2027년 2월 26일",       "2026-03-02", "2027-02-26"),
    ("2026.3.2 - 2027.2.26",                 "2026-03-02", "2027-02-26"),
    ("2026년 3월 2일부터 2027년 2월 26일까지",  "2026-03-02", "2027-02-26"),
    ("2026-03-02 09:00 ~ 2027-02-26 18:00",  "2026-03-02", "2027-02-26"),

    # ── 날짜 하나 + 마감 단서 ──
    ("2026-03-02까지",                        "",           "2026-03-02"),
    ("2026년 3월 2일까지",                     "",           "2026-03-02"),
    ("~ 2026-03-02",                         "",           "2026-03-02"),
    ("신청기한: 2026-03-02",                   "",           "2026-03-02"),
    ("접수마감 2026.3.2",                      "",           "2026-03-02"),

    # ── 날짜 하나 + 시작 단서 ──
    ("2026-03-02부터",                        "2026-03-02", ""),
    ("2026년 3월 2일부터 예산 소진 시까지",      "2026-03-02", ""),
    ("2026-03-02 ~",                         "2026-03-02", ""),

    # ── 단서가 없거나 날짜가 아닌 것 — 비워 둔다 ──
    ("2026-03-02",                           "",           ""),
    ("접수기관별 상이",                        "",           ""),
    ("예산 소진 시까지",                       "",           ""),
    ("상시",                                  "",           ""),
    ("연중 수시",                              "",           ""),
    ("3.2 ~ 3.31",                            "",           ""),   # 연도 없음 — 미지원
    ("매년 3월 ~ 4월",                         "",           ""),   # 연·월만 — 미지원
    ("문의 02-1234-5678",                      "",           ""),   # 전화번호를 날짜로 읽지 않는다
    ("2026-13-02 ~ 2027-02-26",              "",           "2027-02-26"),  # 13월은 건너뛴다
]


def main() -> int:
    failed = 0
    for text, want_start, want_end in CASES:
        got_start, got_end = parse_period(text)
        hit = (got_start, got_end) == (want_start, want_end)
        if not hit:
            failed += 1
        always = "  상시" if any(t in text for t in ALWAYS_TOKENS) else ""
        note = "" if hit else "   ← 기대 %s / %s" % (want_start or "—", want_end or "—")
        print("%s  %-40s start=%-12s end=%-12s%s%s" % (
            "✓" if hit else "✗", text, got_start or "—", got_end or "—", always, note))

    print("\n%d건 중 %d건 통과" % (len(CASES), len(CASES) - failed))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
